#!/usr/bin/env python3
"""Generate the Swift string table from localization/strings.json.

Why a generator instead of hand-written Swift
---------------------------------------------
A translation table typed directly into Swift can drift from the source it claims
to translate: a key gets renamed in the view, the table keeps the old name, and
the window silently falls back to a raw key. Here the JSON is the only source,
the Swift file is generated from it, and tests/test_localization.py fails when the
two disagree - so a missing or stale string is a red build, not a runtime
surprise.

The generator also refuses a table that cannot be used: a key missing one of the
languages, an empty string, or a placeholder that exists in one language and not
the other (a translated format string that drops {count} would print the literal
placeholder at runtime).

Usage
-----
    python3 scripts/gen_localization.py            # rewrite Sources/LocalizationStrings.swift
    python3 scripts/gen_localization.py --check    # exit 1 if the file is out of date
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "localization" / "strings.json"
TARGET = ROOT / "Sources" / "LocalizationStrings.swift"
PLACEHOLDER = re.compile(r"\{(\w+)\}")


def load(path: Path = SOURCE) -> dict:
    data = json.loads(path.read_text(encoding="utf-8"))
    if data.get("schema") != 1:
        raise SystemExit("localization: unsupported schema %r" % data.get("schema"))
    languages = data.get("languages") or {}
    if not languages:
        raise SystemExit("localization: no languages declared")
    if data.get("defaultLanguage") not in languages:
        raise SystemExit("localization: defaultLanguage is not one of the declared languages")
    strings = data.get("strings") or {}
    if not strings:
        raise SystemExit("localization: no strings")
    problems = []
    for key, entry in strings.items():
        missing = [language for language in languages if language not in entry]
        if missing:
            problems.append("%s: missing %s" % (key, ", ".join(missing)))
            continue
        extra = [language for language in entry if language not in languages]
        if extra:
            problems.append("%s: unknown language(s) %s" % (key, ", ".join(extra)))
        tokens = {language: set(PLACEHOLDER.findall(entry[language])) for language in languages}
        first = next(iter(languages))
        for language in languages:
            if tokens[language] != tokens[first]:
                problems.append("%s: placeholders differ between %s and %s (%s vs %s)"
                                % (key, first, language,
                                   sorted(tokens[first]), sorted(tokens[language])))
            if not entry[language].strip():
                problems.append("%s: %s is empty" % (key, language))
    if problems:
        for problem in problems:
            print("localization: %s" % problem, file=sys.stderr)
        raise SystemExit(1)
    return data


def swift_literal(text: str) -> str:
    escaped = (text.replace("\\", "\\\\")
                   .replace('"', '\\"')
                   .replace("\n", "\\n"))
    return '"%s"' % escaped


def render(data: dict) -> str:
    languages = sorted(data["languages"])
    lines = [
        "// Generated by scripts/gen_localization.py from localization/strings.json.",
        "// Do not edit by hand: change the JSON and run the generator instead.",
        "",
        "enum LocalizedStrings {",
        "    static let languages: [String] = [%s]" % ", ".join(swift_literal(l) for l in languages),
        "    static let defaultLanguage = %s" % swift_literal(data["defaultLanguage"]),
        "    static let displayNames: [String: String] = [",
    ]
    for language in languages:
        lines.append("        %s: %s," % (swift_literal(language),
                                         swift_literal(data["languages"][language])))
    lines += ["    ]", "", "    static let table: [String: [String: String]] = ["]
    for key in sorted(data["strings"]):
        lines.append("        %s: [" % swift_literal(key))
        for language in languages:
            lines.append("            %s: %s," % (swift_literal(language),
                                                 swift_literal(data["strings"][key][language])))
        lines.append("        ],")
    lines += ["    ]", "}", ""]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="Generate the Swift string table")
    parser.add_argument("--check", action="store_true",
                        help="fail instead of writing when the generated file is out of date")
    args = parser.parse_args(argv)
    data = load()
    rendered = render(data)
    current = TARGET.read_text(encoding="utf-8") if TARGET.is_file() else ""
    if args.check:
        if current != rendered:
            print("localization: %s is out of date; run python3 scripts/gen_localization.py"
                  % TARGET.relative_to(ROOT), file=sys.stderr)
            return 1
        print("localization: %s is up to date" % TARGET.relative_to(ROOT))
        return 0
    TARGET.write_text(rendered, encoding="utf-8")
    print("localization: wrote %s (%d strings, %d languages)"
          % (TARGET.relative_to(ROOT), len(data["strings"]), len(data["languages"])))
    return 0


if __name__ == "__main__":
    sys.exit(main())
