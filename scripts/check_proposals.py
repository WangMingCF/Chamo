#!/usr/bin/env python3
"""Check the single PRD per proposal and generate its directory (not a lock)."""
import argparse
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[1]
STATES = {'proposed', 'active', 'review', 'merged', 'blocked', 'cancelled'}
DEVICES = {'NAS-DSH', 'Mac-DSH', 'Mac-Claude', 'Mac-Codex'}


def catalogue(root):
    # A linked spec/attachment can escape the reviewable proposal tree.
    def check_layout(path, top=False):
        for item in path.iterdir():
            if item.is_symlink() or not (item.is_dir() or item.is_file()):
                raise ValueError(f'{item.name}: links and special files are not allowed')
            if top:
                if item.is_file() and item.name not in {'README.md', 'INDEX.md'}:
                    raise ValueError(f'{item.name}: unexpected root file')
                if item.is_dir() and item.name.startswith('_') and item.name != '_template':
                    raise ValueError(f'{item.name}: unknown special directory')
            elif item.is_file():
                name = item.name.casefold()
                if (name in {'proposal.json', 'pr.md'}
                        or (name.startswith('prd') and name.endswith('.md') and item.name != 'PRD.md')):
                    raise ValueError(f'{item.name}: conflicting specification')
                if item.name == 'PRD.md' and path.parent != root:
                    raise ValueError(f'{item.name}: nested specification')
            if item.is_dir():
                check_layout(item)
    check_layout(root, top=True)
    rows = []
    for folder in sorted(root.iterdir()):
        if not folder.is_dir() or folder.name == '_template':
            continue
        text = (folder / 'PRD.md').read_text()
        match = re.search(r'^```json\n(.*?)\n```', text, re.M | re.S)
        if not match:
            raise ValueError(f'{folder.name}: missing metadata')
        meta = json.loads(match[1])
        if meta.get('id') != folder.name or not re.fullmatch(r'[a-z0-9-]+', folder.name):
            raise ValueError(f'{folder.name}: invalid id')
        if meta.get('status') not in STATES or meta.get('owner_device') not in DEVICES:
            raise ValueError(f'{folder.name}: invalid state or device')
        for key in ('title', 'branch'):
            if not isinstance(meta.get(key), str) or not meta[key].strip() or any(c in meta[key] for c in '|\n'):
                raise ValueError(f'{folder.name}: invalid {key}')
        if not re.search(r'\bAC-\d+\b', text):
            raise ValueError(f'{folder.name}: acceptance criteria required')
        rows.append(f'| [{meta["title"]}]({folder.name}/PRD.md) | {meta["owner_device"]} | {meta["status"]} | `{meta["branch"]}` |')
    return '\n'.join(['# 需求目录', '', '<!-- Generated by scripts/check_proposals.py --write -->', '',
                     '| 需求 | 执行端 | 状态 | 分支 |', '| --- | --- | --- | --- |', *rows, ''])


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--write', action='store_true')
    args = parser.parse_args()
    path = ROOT/'proposals/INDEX.md'; expected = catalogue(path.parent)
    if args.write:
        path.write_text(expected)
    elif path.read_text() != expected:
        raise SystemExit('proposal index is stale; run scripts/check_proposals.py --write')
    print('proposal catalogue valid')


if __name__ == '__main__':
    main()
